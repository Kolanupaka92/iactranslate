"""Pulumi (Python) renderer — an alternative IaC output to Terraform.

Renders the same validated MigrationPlan as a Pulumi program, proving the
pipeline is renderer-agnostic. Supports all three targets: AWS (pulumi-aws),
Azure (pulumi-azure), and GCP (pulumi-gcp).

Deterministic string generation — no AI. The emitted `__main__.py` is
syntactically valid Python (compiled in tests).
"""
from __future__ import annotations

import hashlib
import re
from typing import Dict, List

from ..generator.renderer import _rfc1035_slug, data_volumes, machine_slugs, windows_computer_name
from ..graph import assign_subnets, public_instances
from ..models import MigrationPlan, SubnetTier, resource_prefix, terraform_safe_name
from ..targets.base import Target


class RendererNotSupportedError(ValueError):
    pass


def _py_str(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _ingress_block(rule) -> str:
    cidrs = ", ".join(_py_str(c) for c in rule.cidr_blocks)
    return (
        "        {"
        f'"description": {_py_str(rule.description)}, '
        f'"protocol": {_py_str(rule.protocol)}, '
        f'"from_port": {rule.from_port}, "to_port": {rule.to_port}, '
        f'"cidr_blocks": [{cidrs}]'
        "},"
    )


#: What an adopted server keeps as it is.
_ADOPTED_IGNORES = ('["ami", "instanceType", "subnetId", "vpcSecurityGroupIds", '
                    '"rootBlockDevice", "associatePublicIpAddress", "iamInstanceProfile", "tags", "tagsAll"]')


def _aws_main(plan: MigrationPlan, target: Target) -> str:
    net = plan.network
    subnet_of = assign_subnets(plan)
    sg_resource = {sg.name: sg.resource_name for sg in net.security_groups}
    has_https = any(listener.protocol == "HTTPS" for lb in net.load_balancers for listener in lb.listeners)

    lines: List[str] = [
        f'"""Pulumi program generated by IaCTranslate — {plan.project_name} (AWS).',
        "",
        "Equivalent to the Terraform output; deploy with `pulumi up`.",
        '"""',
        "import pulumi",
        "import pulumi_aws as aws",
        "",
        f"region = {_py_str(plan.region)}",
        'provider = aws.Provider("aws", region=region)',
        "opts = pulumi.ResourceOptions(provider=provider)",
        'azs = aws.get_availability_zones(state="available")',
    ]
    if has_https:
        lines += [
            "config = pulumi.Config()",
            '# Required for HTTPS listeners - no ACM certificate can be known at '
            "generation time.",
            'acm_certificate_arn = config.get("acmCertificateArn") or ""',
        ]
    lines += [
        "",
        "# --- Network -------------------------------------------------------------",
        'vpc = aws.ec2.Vpc(',
        '    "vpc",',
        f"    cidr_block={_py_str(net.vpc_cidr)},",
        "    enable_dns_hostnames=True,",
        "    enable_dns_support=True,",
        f'    tags={{"Name": {_py_str(plan.project_name + "-vpc")}}},',
        "    opts=opts,",
        ")",
    ]

    if net.internet_gateway:
        lines += [
            'igw = aws.ec2.InternetGateway("igw", vpc_id=vpc.id,',
            f'    tags={{"Name": {_py_str(plan.project_name + "-igw")}}}, opts=opts)',
        ]

    lines.append("")
    for s in net.subnets:
        lines += [
            f"subnet_{s.resource_name} = aws.ec2.Subnet(",
            f"    {_py_str(s.resource_name)},",
            "    vpc_id=vpc.id,",
            f"    cidr_block={_py_str(s.cidr)},",
            f"    availability_zone=azs.names[{s.availability_zone_index}],",
            # Each machine says whether it gets a public address (ADR 0095).
            "    map_public_ip_on_launch=False,",
            f'    tags={{"Name": {_py_str(s.name)}, "Tier": {_py_str(s.tier.value)}}},',
            "    opts=opts,",
            ")",
        ]

    # Routing, as Terraform's: public subnets out through the internet gateway,
    # private ones through NAT. Without it nothing could reach the public load
    # balancer and private machines had no way out (ADR 0097).
    lines += ["", "# --- Routing ---------------------------------------------------------------"]
    public = [sn for sn in net.subnets if sn.tier == SubnetTier.PUBLIC]
    private = [sn for sn in net.subnets if sn.tier == SubnetTier.PRIVATE]
    if net.internet_gateway:
        lines += [
            'rt_public = aws.ec2.RouteTable("public", vpc_id=vpc.id,',
            '    routes=[{"cidr_block": "0.0.0.0/0", "gateway_id": igw.id}],',
            f'    tags={{"Name": {_py_str(plan.project_name + "-public-rt")}}}, opts=opts)',
        ]
        lines += [f'aws.ec2.RouteTableAssociation("{sn.resource_name}", subnet_id=subnet_{sn.resource_name}.id, '
                  'route_table_id=rt_public.id, opts=opts)' for sn in public]
    if net.nat_gateway and public and private:
        lines += [
            'nat_eip = aws.ec2.Eip("nat", domain="vpc",',
            f'    tags={{"Name": {_py_str(plan.project_name + "-nat-eip")}}}, opts=opts)',
            f'nat = aws.ec2.NatGateway("nat", allocation_id=nat_eip.id, subnet_id=subnet_{public[0].resource_name}.id,',
            f'    tags={{"Name": {_py_str(plan.project_name + "-nat")}}},',
            "    opts=pulumi.ResourceOptions(provider=provider"
            + (", depends_on=[igw]" if net.internet_gateway else "") + "))",
            'rt_private = aws.ec2.RouteTable("private", vpc_id=vpc.id,',
            '    routes=[{"cidr_block": "0.0.0.0/0", "nat_gateway_id": nat.id}],',
            f'    tags={{"Name": {_py_str(plan.project_name + "-private-rt")}}}, opts=opts)',
        ]
        lines += [f'aws.ec2.RouteTableAssociation("{sn.resource_name}", subnet_id=subnet_{sn.resource_name}.id, '
                  'route_table_id=rt_private.id, opts=opts)' for sn in private]

    lines += ["", "# --- Security groups -----------------------------------------------------"]
    for sg in net.security_groups:
        ingress = "\n".join(_ingress_block(r) for r in sg.ingress)
        lines += [
            f"sg_{sg.resource_name} = aws.ec2.SecurityGroup(",
            f"    {_py_str(sg.resource_name)},",
            "    vpc_id=vpc.id,",
            f"    description={_py_str(sg.description or sg.name)},",
            "    ingress=[",
            ingress,
            "    ],",
            '    egress=[{"protocol": "-1", "from_port": 0, "to_port": 0, '
            '"cidr_blocks": ["0.0.0.0/0"]}],',
            f'    tags={{"Name": {_py_str(sg.name)}}},',
            "    opts=opts,",
            ")",
        ]

    # AMI lookups, one per distinct OS image.
    lines += ["", "# --- AMI lookups ---------------------------------------------------------"]
    image_keys = sorted({c.image_key for c in plan.compute})
    for key in image_keys:
        ref = target.image_reference(key)
        owners = ", ".join(_py_str(o) for o in ref.get("owners", []))
        name = _py_str(ref.get("name", "*"))
        var = terraform_safe_name(key)
        lines += [
            f"ami_{var} = aws.ec2.get_ami(",
            "    most_recent=True,",
            f"    owners=[{owners}],",
            f'    filters=[{{"name": "name", "values": [{name}]}},',
            '             {"name": "virtualization-type", "values": ["hvm"]}],',
            ")",
        ]

    public_aws = public_instances(plan)
    # Instances.
    lines += ["", "# --- Instances -----------------------------------------------------------"]
    for c in plan.compute:
        ami_var = terraform_safe_name(c.image_key)
        subnet_res = subnet_of[c.vm_name]
        sg_res = sg_resource.get(c.security_group)
        sg_ref = f"sg_{sg_res}.id" if sg_res else "None"
        lines += [
            f"inst_{c.resource_name} = aws.ec2.Instance(",
            f"    {_py_str(c.resource_name)},",
            f"    instance_type={_py_str(c.instance_type)},",
            f"    ami=ami_{ami_var}.id,",
            f"    subnet_id=subnet_{subnet_res}.id,",
            f"    associate_public_ip_address={c.vm_name in public_aws},",
            f"    vpc_security_group_ids=[{sg_ref}],",
            # Encrypted, as Terraform's are (ADR 0093).
            f'    root_block_device={{"volume_size": {c.root_volume_gib}, "volume_type": "gp3", "encrypted": True}},',
            f'    tags={{"Name": {_py_str(c.vm_name)}, "Tier": {_py_str(c.tier.value)}, '
            f'"Environment": {_py_str(c.environment.value)}}},',
            # A newer image must not replace a running server (ADR 0090).
            '    opts=pulumi.ResourceOptions(provider=provider, '
            + (
                # Brownfield: adopt the running server as it is. Pulumi refuses an
                # import whose inputs differ, so everything that may is ignored;
                # resize it afterwards on purpose (ADR 0091).
                f"ignore_changes={_ADOPTED_IGNORES}, import_={_py_str(c.external_id)}),"
                if c.external_id else 'ignore_changes=["ami"]),'
            ),
            ")",
        ]

    volumes = data_volumes(plan.compute)
    if volumes:
        lines += ["", "# --- Data volumes --------------------------------------------------------"]
    for v in volumes:
        inst, vol = f"inst_{v['instance_resource']}", f"vol_{v['resource_name']}"
        lines += [
            f"{vol} = aws.ebs.Volume(",
            f"    {_py_str(v['resource_name'])},",
            f"    availability_zone={inst}.availability_zone,",
            f'    size={v["size"]}, type="gp3", encrypted=True,',
            f'    tags={{"Name": {_py_str(v["vm_name"] + "-data")}, "SourceVM": {_py_str(v["vm_name"])}}},',
            "    opts=opts,",
            ")",
            "aws.ec2.VolumeAttachment(",
            f"    {_py_str(v['resource_name'])},",
            f"    device_name={_py_str(v['device'])}, volume_id={vol}.id, instance_id={inst}.id,",
            "    opts=opts,",
            ")",
        ]

    if net.load_balancers:
        lines += ["", "# --- Load balancers --------------------------------------------------------"]
        for lb in net.load_balancers:
            lb_subnets = ", ".join(f"subnet_{s.resource_name}.id" for s in net.subnets if s.tier == lb.subnet_tier)
            lb_sg = sg_resource.get(lb.security_group)
            lines += [
                f"lb_{lb.resource_name} = aws.lb.LoadBalancer(",
                f"    {_py_str(lb.resource_name)},",
                # Named as Terraform names it: AWS allows only letters, digits and
                # hyphens, and Pulumi's default name keeps the label's "_" (ADR 0096).
                f"    name={_py_str(lb.resource_name.replace('_', '-'))},",
                f'    internal={not lb.internet_facing},',
                '    load_balancer_type="application",',
                f"    security_groups=[sg_{lb_sg}.id],",
                f"    subnets=[{lb_subnets}],",
                f'    tags={{"Name": {_py_str(lb.name)}}},',
                "    opts=opts,",
                ")",
            ]
            for listener in lb.listeners:
                tg = f"tg_{lb.resource_name}_{listener.listener_port}"
                lines += [
                    f"{tg} = aws.lb.TargetGroup(",
                    f"    {_py_str(lb.resource_name + '-' + str(listener.listener_port))},",
                    f"    name={_py_str((lb.resource_name + '-' + str(listener.listener_port)).replace('_', '-'))},",
                    f"    port={listener.target_port},",
                    f"    protocol={_py_str(listener.protocol)},",
                    "    vpc_id=vpc.id,",
                    f'    health_check={{"path": {_py_str(lb.health_check_path)}}},',
                    "    opts=opts,",
                    ")",
                ]
                for vm_name in lb.targets:
                    c = next(cc for cc in plan.compute if cc.vm_name == vm_name)
                    lines += [
                        "aws.lb.TargetGroupAttachment(",
                        f"    {_py_str(f'{lb.resource_name}-{listener.listener_port}-{c.resource_name}')},",
                        f"    target_group_arn={tg}.arn,",
                        f"    target_id=inst_{c.resource_name}.id,",
                        f"    port={listener.target_port},",
                        "    opts=opts,",
                        ")",
                    ]
                https = listener.protocol == "HTTPS"
                listener_kwargs = (
                    ['    ssl_policy="ELBSecurityPolicy-TLS13-1-2-2021-06",',
                     "    certificate_arn=acm_certificate_arn,"]
                    if https else []
                )
                body = [
                    "aws.lb.Listener(",
                    f"    {_py_str(lb.resource_name + '-' + str(listener.listener_port))},",
                    f"    load_balancer_arn=lb_{lb.resource_name}.arn,",
                    f"    port={listener.listener_port},",
                    f"    protocol={_py_str(listener.protocol)},",
                    *listener_kwargs,
                    f'    default_actions=[{{"type": "forward", "target_group_arn": {tg}.arn}}],',
                    "    opts=opts,",
                    ")",
                ]
                if https:
                    # AWS refuses an HTTPS listener without a certificate (ADR 0094).
                    body = ["if acm_certificate_arn:"] + ["    " + b for b in body] + [
                        "else:",
                        f'    pulumi.log.warn("No HTTPS on {lb.name}: set acmCertificateArn to serve it.")',
                    ]
                lines += body

    lines += [
        "",
        'pulumi.export("vpc_id", vpc.id)',
        'pulumi.export("instance_count", ' + str(plan.vm_count) + ")",
        "",
    ]
    return "\n".join(lines)


def _azure_main(plan: MigrationPlan, target: Target) -> str:
    net = plan.network
    slugs = machine_slugs(plan.compute)  # each machine's own cloud name
    subnet_of = assign_subnets(plan)
    sg_resource = {sg.name: sg.resource_name for sg in net.security_groups}
    # Every Azure resource is named as in Terraform. Pulumi's own names (label
    # plus a random suffix) break its 24-character limit on several Azure
    # types and carry underscores (ADR 0099).
    prefix = resource_prefix(plan.project_name)

    lines: List[str] = [
        f'"""Pulumi program generated by IaCTranslate — {plan.project_name} (Azure)."""',
        "import pulumi",
        "import pulumi_azure as azure",
        "",
        "config = pulumi.Config()",
        'admin_username = config.get("adminUsername") or "azureuser"',
        'admin_password = config.get_secret("adminPassword") or "REPLACE_ME_Str0ng!Pass"',
        'admin_ssh_public_key = config.get("adminSshPublicKey") or "ssh-rsa REPLACE_ME"',
        f"location = {_py_str(plan.region)}",
        "",
        "rg = azure.core.ResourceGroup(",
        '    "rg",',
        f"    name={_py_str(resource_prefix(plan.project_name) + '-rg')},",
        "    location=location,",
        ")",
        "vnet = azure.network.VirtualNetwork(",
        '    "vnet",',
        f"    name={_py_str(prefix + '-vnet')},",
        "    resource_group_name=rg.name,",
        "    location=rg.location,",
        f"    address_spaces=[{_py_str(net.vpc_cidr)}],",
        ")",
    ]

    for s in net.subnets:
        lines += [
            f"subnet_{s.resource_name} = azure.network.Subnet(",
            f"    {_py_str(s.resource_name)},",
            f"    name={_py_str(prefix + '-' + _rfc1035_slug(s.resource_name))},",
            "    resource_group_name=rg.name,",
            "    virtual_network_name=vnet.name,",
            f"    address_prefixes=[{_py_str(s.cidr)}],",
            ")",
        ]

    # Private machines' way out, as in Terraform (ADR 0100).
    if net.nat_gateway:
        lines += [
            "nat_ip = azure.network.PublicIp(",
            '    "nat",',
            f"    name={_py_str(prefix + '-nat-ip')},",
            "    resource_group_name=rg.name, location=rg.location,",
            '    allocation_method="Static", sku="Standard",',
            ")",
            "nat = azure.network.NatGateway(",
            '    "nat",',
            f"    name={_py_str(prefix + '-nat')},",
            "    resource_group_name=rg.name, location=rg.location,",
            '    sku_name="Standard",',
            ")",
            'azure.network.NatGatewayPublicIpAssociation("nat", nat_gateway_id=nat.id, public_ip_address_id=nat_ip.id)',
        ]
        for s in net.subnets:
            if s.tier == SubnetTier.PRIVATE:
                lines.append(
                    f"azure.network.SubnetNatGatewayAssociation({_py_str(s.resource_name)}, "
                    f"subnet_id=subnet_{s.resource_name}.id, nat_gateway_id=nat.id)"
                )

    # NSGs with security rules.
    for sg in net.security_groups:
        rules = []
        for i, r in enumerate(sg.ingress):
            port = f"{r.from_port}" if r.from_port == r.to_port else f"{r.from_port}-{r.to_port}"
            src = r.cidr_blocks[0] if r.cidr_blocks else "*"
            rules.append(
                "        {"
                f'"name": {_py_str("rule-" + str(i))}, "priority": {100 + i * 10}, '
                '"direction": "Inbound", "access": "Allow", '
                f'"protocol": {_py_str(r.protocol.capitalize())}, '
                '"source_port_range": "*", '
                f'"destination_port_range": {_py_str(port)}, '
                f'"source_address_prefix": {_py_str(src)}, '
                '"destination_address_prefix": "*"},'
            )
        lines += [
            f"nsg_{sg.resource_name} = azure.network.NetworkSecurityGroup(",
            f"    {_py_str(sg.resource_name)},",
            f"    name={_py_str(prefix + '-' + _rfc1035_slug(sg.resource_name))},",
            "    resource_group_name=rg.name,",
            "    location=rg.location,",
            "    security_rules=[",
            *rules,
            "    ],",
            ")",
        ]

    backend_pool_ref_by_vm_name: Dict[str, str] = {}
    if net.load_balancers:
        lines += ["", "# --- Load balancers ---------------------------------------------------"]
        for lb in net.load_balancers:
            lb_var = f"lb_{lb.resource_name}"
            if lb.internet_facing:
                lines += [
                    f"pip_{lb.resource_name} = azure.network.PublicIp(",
                    f"    {_py_str(lb.resource_name)},",
                    f"    name={_py_str(lb.name + '-pip')},",
                    "    resource_group_name=rg.name, location=rg.location,",
                    '    allocation_method="Static", sku="Standard",',
                    ")",
                ]
                frontend = f'{{"name": "frontend", "public_ip_address_id": pip_{lb.resource_name}.id}}'
            else:
                first_subnet = next(s for s in net.subnets if s.tier == lb.subnet_tier)
                frontend = (
                    '{"name": "frontend", '
                    f'"subnet_id": subnet_{first_subnet.resource_name}.id, '
                    '"private_ip_address_allocation": "Dynamic"}'
                )
            lines += [
                f"{lb_var} = azure.lb.LoadBalancer(",
                f"    {_py_str(lb.resource_name)},",
                f"    name={_py_str(lb.name)},",
                "    resource_group_name=rg.name, location=rg.location,",
                '    sku="Standard",',
                f"    frontend_ip_configurations=[{frontend}],",
                ")",
                f"pool_{lb.resource_name} = azure.lb.BackendAddressPool(",
                f"    {_py_str(lb.resource_name)},",
                '    name="backendPool",',
                f"    loadbalancer_id={lb_var}.id,",
                ")",
            ]
            for listener in lb.listeners:
                suffix = f"{lb.resource_name}_{listener.listener_port}"
                lines += [
                    f"probe_{suffix} = azure.lb.Probe(",
                    f"    {_py_str(suffix)},",
                    f"    name={_py_str('probe' + str(listener.listener_port))},",
                    f"    loadbalancer_id={lb_var}.id,",
                    f'    protocol="Tcp", port={listener.target_port},',
                    ")",
                    "azure.lb.Rule(",
                    f"    {_py_str(suffix)},",
                    f"    name={_py_str('rule' + str(listener.listener_port))},",
                    f"    loadbalancer_id={lb_var}.id,",
                    '    protocol="Tcp",',
                    f"    frontend_port={listener.listener_port}, backend_port={listener.target_port},",
                    '    frontend_ip_configuration_name="frontend",',
                    f"    backend_address_pool_ids=[pool_{lb.resource_name}.id],",
                    f"    probe_id=probe_{suffix}.id,",
                    ")",
                ]
            for vm_name in lb.targets:
                backend_pool_ref_by_vm_name[vm_name] = f"pool_{lb.resource_name}.id"

    # One identity per tier with no role assignments, as Terraform's (ADR 0057, 0100).
    lines += ["", "# --- Identities (one per tier, no roles) ----------------------------------"]
    for tier in sorted({c.tier.value for c in plan.compute}):
        lines += [
            f"id_{tier} = azure.authorization.UserAssignedIdentity(",
            f"    {_py_str('id_' + tier)},",
            f"    name={_py_str(prefix + '-' + tier)},",
            "    resource_group_name=rg.name, location=rg.location,",
            ")",
        ]

    public_vms = public_instances(plan)
    for c in plan.compute:
        ref = target.image_reference(c.image_key)
        nic = f"nic_{c.resource_name}"
        subnet_res = subnet_of[c.vm_name]
        sg_res = sg_resource.get(c.security_group)
        is_windows = c.image_key.startswith("windows")
        backend_pool_ref = backend_pool_ref_by_vm_name.get(c.vm_name)
        # A fronted instance gets its public entry point via the load balancer,
        # not its own public IP - giving it one too would bypass the LB.
        if c.vm_name in public_vms:
            lines += [
                f"pip_{c.resource_name} = azure.network.PublicIp(",
                f"    {_py_str(c.resource_name)},",
                f"    name={_py_str(slugs[c.resource_name] + '-pip')},",
                "    resource_group_name=rg.name, location=rg.location,",
                '    allocation_method="Static", sku="Standard",',
                ")",
            ]
        ip_cfg = (
            '        "name": "internal", '
            f'"subnet_id": subnet_{subnet_res}.id, '
            '"private_ip_address_allocation": "Dynamic"'
        )
        if c.vm_name in public_vms:
            ip_cfg += f', "public_ip_address_id": pip_{c.resource_name}.id'
        lines += [
            f"{nic} = azure.network.NetworkInterface(",
            f"    {_py_str(c.resource_name)},",
            f"    name={_py_str(slugs[c.resource_name] + '-nic')},",
            "    resource_group_name=rg.name, location=rg.location,",
            "    ip_configurations=[{" + ip_cfg + "}],",
            ")",
        ]
        if sg_res:
            lines += [
                "azure.network.NetworkInterfaceSecurityGroupAssociation(",
                f"    {_py_str(c.resource_name)},",
                f"    network_interface_id={nic}.id,",
                f"    network_security_group_id=nsg_{sg_res}.id,",
                ")",
            ]
        if backend_pool_ref:
            lines += [
                "azure.network.NetworkInterfaceBackendAddressPoolAssociation(",
                f"    {_py_str(c.resource_name)},",
                f"    network_interface_id={nic}.id,",
                '    ip_configuration_name="internal",',
                f"    backend_address_pool_id={backend_pool_ref},",
                ")",
            ]
        vm_type = "WindowsVirtualMachine" if is_windows else "LinuxVirtualMachine"
        cred = (
            "    admin_password=admin_password,"
            if is_windows
            else "    admin_ssh_keys=[{\"username\": admin_username, "
                 '"public_key": admin_ssh_public_key}],'
        )
        lines += [
            f"inst_{c.resource_name} = azure.compute.{vm_type}(",
            f"    {_py_str(c.resource_name)},",
            # Pulumi's own name would carry the underscore and a random suffix,
            # which Azure refuses; Windows allows 15 characters (ADR 0099).
            f"    name={_py_str(slugs[c.resource_name])},",
            *([f"    computer_name={_py_str(windows_computer_name(slugs[c.resource_name]))},"] if is_windows else []),
            f'    identity={{"type": "UserAssigned", "identity_ids": [id_{c.tier.value}.id]}},',
            "    resource_group_name=rg.name, location=rg.location,",
            f"    size={_py_str(c.instance_type)},",
            "    admin_username=admin_username,",
            cred,
            f"    network_interface_ids=[{nic}.id],",
            '    os_disk={"caching": "ReadWrite", "storage_account_type": "StandardSSD_LRS", '
            f'"disk_size_gb": {c.root_volume_gib}}},',
            "    source_image_reference={"
            f'"publisher": {_py_str(ref["publisher"])}, '
            f'"offer": {_py_str(ref["offer"])}, '
            f'"sku": {_py_str(ref["sku"])}, "version": "latest"}},',
            # Azure turns the agent's platform updates on by itself (ADR 0099).
            '    opts=pulumi.ResourceOptions(ignore_changes=["vmAgentPlatformUpdatesEnabled"]),',
            ")",
        ]

    volumes = data_volumes(plan.compute)
    if volumes:
        lines += ["", "# --- Data disks ----------------------------------------------------------"]
    for v in volumes:
        disk = f"disk_{v['resource_name']}"
        lines += [
            f"{disk} = azure.compute.ManagedDisk(",
            f"    {_py_str(v['resource_name'])},",
            # Terraform's name. Pulumi's own (label plus random suffix) passes its
            # 24-character limit for disks on long machine names (ADR 0099).
            f"    name={_py_str(slugs[v['instance_resource']] + '-data-' + str(v['lun']))},",
            "    resource_group_name=rg.name, location=rg.location,",
            f'    storage_account_type="StandardSSD_LRS", create_option="Empty", disk_size_gb={v["size"]},',
            f'    tags={{"SourceVM": {_py_str(v["vm_name"])}}},',
            ")",
            "azure.compute.DataDiskAttachment(",
            f"    {_py_str(v['resource_name'])},",
            f"    managed_disk_id={disk}.id, virtual_machine_id=inst_{v['instance_resource']}.id,",
            f'    lun={v["lun"]}, caching="ReadWrite",',
            ")",
        ]

    lines += ["", 'pulumi.export("resource_group", rg.name)', ""]
    return "\n".join(lines)


def _gname(label: str) -> str:
    """A Pulumi resource name Google accepts.

    Pulumi names a resource after it, plus a hyphen and seven characters, and
    Google allows only lowercase letters, digits and hyphens, starting with a
    letter, up to 63. Labels like `public_0` were refused (ADR 0097).
    """
    name = re.sub(r"[^a-z0-9-]+", "-", label.lower()).strip("-") or "r"
    if not name[0].isalpha():
        name = "r-" + name
    return name[:55].rstrip("-")


def _gcp_account_id(project_name: str, tier: str) -> str:
    """A service account id Google accepts (6 to 30 characters), as Terraform's."""
    slug = _rfc1035_slug(resource_prefix(project_name))
    room = 29 - len(tier)
    if len(slug) > room:
        digest = hashlib.md5(slug.encode()).hexdigest()[:4]  # nosec B324: a name, not security
        slug = f"{slug[:room - 5].rstrip('-')}-{digest}"
    account = f"{slug}-{tier}"
    return account if len(account) >= 6 else f"{account}-sa"


def _gcp_main(plan: MigrationPlan, target: Target) -> str:
    slugs = machine_slugs(plan.compute)  # each machine's own cloud name
    net = plan.network
    subnet_of = assign_subnets(plan)

    lines: List[str] = [
        f'"""Pulumi program generated by IaCTranslate — {plan.project_name} (GCP)."""',
        "import pulumi",
        "import pulumi_gcp as gcp",
        "",
        "config = pulumi.Config()",
        'project = config.get("gcpProject") or "REPLACE_ME_PROJECT_ID"',
        f"region = {_py_str(plan.region)}",
        f"zone = {_py_str(plan.region + '-a')}",
        "",
        "network = gcp.compute.Network(",
        '    "network",',
        "    auto_create_subnetworks=False,",
        "    project=project,",
        ")",
    ]

    for s in net.subnets:
        lines += [
            f"subnet_{s.resource_name} = gcp.compute.Subnetwork(",
            f"    {_py_str(_gname(s.resource_name))},",
            f"    ip_cidr_range={_py_str(s.cidr)},",
            "    region=region, network=network.id,",
            "    private_ip_google_access=True, project=project,",
            ")",
        ]

    if net.nat_gateway:
        # Private machines' way out, as Terraform's router and NAT (ADR 0097).
        lines += [
            'router = gcp.compute.Router("router", region=region, network=network.id, project=project)',
            'gcp.compute.RouterNat("nat", router=router.name, region=region, project=project,',
            '    nat_ip_allocate_option="AUTO_ONLY",',
            '    source_subnetwork_ip_ranges_to_nat="ALL_SUBNETWORKS_ALL_IP_RANGES")',
            "",
        ]

    # A firewall per security group, scoped to its tag.
    for sg in net.security_groups:
        tcp_ports = sorted({str(r.from_port) for r in sg.ingress if r.protocol.lower() == "tcp"})
        ports = ", ".join(_py_str(p) for p in tcp_ports) or '"22"'
        srcs = sorted({c for r in sg.ingress for c in r.cidr_blocks}) or ["0.0.0.0/0"]
        src_ranges = ", ".join(_py_str(c) for c in srcs)
        lines += [
            f"fw_{sg.resource_name} = gcp.compute.Firewall(",
            f"    {_py_str(_gname(sg.resource_name))},",
            "    network=network.name, project=project,",
            '    allows=[{"protocol": "tcp", "ports": [' + ports + "]}],",
            f"    source_ranges=[{src_ranges}],",
            f"    target_tags=[{_py_str(sg.name)}],",
            ")",
        ]

    # A service account per tier with no roles, as Terraform's default identity
    # (ADR 0057). Without one, Google's agent on the machine has no credentials
    # (ADR 0098).
    lines += ["", "# --- Service accounts (one per tier, no roles) ----------------------------"]
    for tier in sorted({c.tier.value for c in plan.compute}):
        lines += [
            f"sa_{tier} = gcp.serviceaccount.Account(",
            f"    {_py_str(_gname(tier + '-sa'))},",
            f"    account_id={_py_str(_gcp_account_id(plan.project_name, tier))},",
            f"    display_name={_py_str(f'{tier} tier ({plan.project_name})')},",
            "    project=project,",
            ")",
        ]

    public_vms = public_instances(plan)
    for c in plan.compute:
        ref = target.image_reference(c.image_key)
        subnet_res = subnet_of[c.vm_name]
        # A fronted instance's public entry point is the load balancer, not its
        # own ephemeral external IP.
        access = "[{}]" if c.vm_name in public_vms else "[]"  # [{}] = one ephemeral external IP
        lines += [
            f"inst_{c.resource_name} = gcp.compute.Instance(",
            f"    {_py_str(_gname(c.resource_name))},",
            # The machine's own name, as Terraform gives it (ADR 0097).
            f"    name={_py_str(slugs[c.resource_name])},",
            f'    service_account={{"email": sa_{c.tier.value}.email, "scopes": ["cloud-platform"]}},',
            f"    machine_type={_py_str(c.instance_type)},",
            "    zone=zone, project=project, allow_stopping_for_update=True,",
            f"    tags=[{_py_str(c.security_group)}],",
            '    boot_disk={"initialize_params": {"image": '
            f'{_py_str(ref["image"])}, "size": {c.root_volume_gib}, "type": "pd-balanced"}}}},',
            '    network_interfaces=[{"subnetwork": subnet_'
            f'{subnet_res}.id, "access_configs": {access}}}],',
            f'    labels={{"tier": {_py_str(c.tier.value)}, '
            f'"environment": {_py_str(c.environment.value)}}},',
            # Data disks are attached below, and a newer image must not replace
            # a running server (ADR 0090).
            '    opts=pulumi.ResourceOptions(ignore_changes=["attachedDisks", '
            '"bootDisk.initializeParams.image"]),',
            ")",
        ]

    volumes = data_volumes(plan.compute)
    if volumes:
        lines += ["", "# --- Data disks ---------------------------------------------------------"]
    for v in volumes:
        disk = f"disk_{v['resource_name']}"
        lines += [
            f"{disk} = gcp.compute.Disk(",
            f"    {_py_str(_gname(v['resource_name']))},",
            f'    zone=zone, project=project, size={v["size"]}, type="pd-balanced",',
            ")",
            "gcp.compute.AttachedDisk(",
            f"    {_py_str(_gname(v['resource_name']))},",
            f"    disk={disk}.id, instance=inst_{v['instance_resource']}.id, zone=zone, project=project,",
            ")",
        ]

    if net.load_balancers:
        lines += ["", "# --- Load balancers -----------------------------------------------------"]
        for lb in net.load_balancers:
            member_refs = ", ".join(
                f"inst_{c.resource_name}.self_link" for c in plan.compute if c.vm_name in lb.targets
            )
            if lb.internet_facing:
                lines += [
                    f"hc_{lb.resource_name} = gcp.compute.HttpHealthCheck(",
                    f"    {_py_str(_gname(lb.resource_name))},",
                    f"    request_path={_py_str(lb.health_check_path)}, port={lb.listeners[0].target_port},",
                    "    project=project,",
                    ")",
                    # One address for every port (ADR 0098).
                    f"addr_{lb.resource_name} = gcp.compute.Address(",
                    f"    {_py_str(_gname(lb.resource_name + '-ip'))},",
                    "    region=region, project=project,",
                    ")",
                    f"pool_{lb.resource_name} = gcp.compute.TargetPool(",
                    f"    {_py_str(_gname(lb.resource_name))},",
                    "    region=region, project=project,",
                    f"    health_checks=hc_{lb.resource_name}.self_link,",
                    f"    instances=[{member_refs}],",
                    ")",
                ]
                for listener in lb.listeners:
                    lines += [
                        "gcp.compute.ForwardingRule(",
                        f"    {_py_str(_gname(f'{lb.resource_name}-{listener.listener_port}'))},",
                        "    region=region, project=project,",
                        f"    ip_address=addr_{lb.resource_name}.address,",
                        f'    port_range={_py_str(str(listener.listener_port))},',
                        f"    target=pool_{lb.resource_name}.self_link,",
                        ")",
                    ]
            else:
                lines += [
                    f"ig_{lb.resource_name} = gcp.compute.InstanceGroup(",
                    f"    {_py_str(_gname(lb.resource_name))},",
                    "    zone=zone, project=project,",
                    f"    instances=[{member_refs}],",
                    ")",
                    f"hc_{lb.resource_name} = gcp.compute.HealthCheck(",
                    f"    {_py_str(_gname(lb.resource_name))},",
                    "    project=project,",
                    f'    tcp_health_check={{"port": {lb.listeners[0].target_port}}},',
                    ")",
                    f"bes_{lb.resource_name} = gcp.compute.RegionBackendService(",
                    f"    {_py_str(_gname(lb.resource_name))},",
                    '    region=region, project=project, protocol="TCP",',
                    '    load_balancing_scheme="INTERNAL",',
                    f"    health_checks=hc_{lb.resource_name}.self_link,",
                    f'    backends=[{{"group": ig_{lb.resource_name}.self_link}}],',
                    ")",
                ]
                lines += [
                    "gcp.compute.Firewall(  # Google's health probes",
                    f"    {_py_str(_gname(f'{lb.resource_name}-probes'))},",
                    "    network=network.id, project=project,",
                    f'    allows=[{{"protocol": "tcp", "ports": ["{lb.listeners[0].target_port}"]}}],',
                    '    source_ranges=["35.191.0.0/16"],',
                    f"    target_tags=[{_py_str(lb.security_group)}],",
                    ")",
                ]
                first_subnet = next(s for s in net.subnets if s.tier == lb.subnet_tier)
                for listener in lb.listeners:
                    lines += [
                        "gcp.compute.ForwardingRule(",
                        f"    {_py_str(_gname(f'{lb.resource_name}-{listener.listener_port}'))},",
                        "    region=region, project=project,",
                        '    load_balancing_scheme="INTERNAL",',
                        "    network=network.id,",
                        f"    subnetwork=subnet_{first_subnet.resource_name}.id,",
                        f"    backend_service=bes_{lb.resource_name}.self_link,",
                        f'    ports=[{_py_str(str(listener.listener_port))}],',
                        ")",
                    ]

    lines += ["", 'pulumi.export("network", network.name)', ""]
    return "\n".join(lines)


