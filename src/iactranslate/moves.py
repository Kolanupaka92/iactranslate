"""Terraform `moved` blocks for machines renamed between two inventory snapshots.

Resource labels are derived from VM names (ADR 0070 explains why they stay that
way), so renaming a machine in vCenter renames its Terraform resources — and
Terraform plans a renamed resource as destroy-and-recreate. For a VM that is a
production outage presented as a routine change.

A `moved` block tells Terraform the object at the old address *is* the object
at the new one. Two facts make generating them possible without keeping any
state from earlier runs:

  * the VM UUID says which machine in the new snapshot is which machine in the
    old one, whatever it is now called (`diff.py`); and
  * labels are a pure function of the inventory, so rendering the *old*
    snapshot reproduces exactly the addresses that run produced.

So both snapshots are rendered for the same target, and every address that
exists only in the old render is paired with the address that replaced it, by
substituting the machine's old label for its new one. A pairing is emitted only
when that new address exists in the new render — never a `moved` block whose
destination the config does not declare. Whatever cannot be paired is reported
rather than guessed at: those really are creations and destructions.

This also catches the indirect case. Distinct names that collapse onto one
label get suffixes (`web_01`, `web_01_2`), so renaming one machine can shift
another's label even though *that* machine was not renamed.

Read-only analysis (ADR 0007): plans and renders in memory, writes nothing.
"""
from __future__ import annotations

import re
from typing import Dict, List, Optional, Set, Tuple

from pydantic import BaseModel, Field

from .agents import build_migration_plan
from .generator.renderer import build_files
from .models import NormalizedVM
from .targets import get_target

_RESOURCE = re.compile(r'^\s*resource\s+"([A-Za-z0-9_]+)"\s+"([A-Za-z0-9_-]+)"', re.MULTILINE)

Address = Tuple[str, str]  # (resource type, label)


class Move(BaseModel):
    from_address: str = Field(description="e.g. aws_instance.app01")
    to_address: str
    vm_name: str = Field(description="The machine, by its name in the newer snapshot")


class Conflict(BaseModel):
    """A move `moved` blocks cannot express, with the state commands that can.

    Terraform chains `moved` blocks: A→B plus B→C sends the object at A to C.
    So when a rename hands one machine's old address to another (`web-01`
    renamed, `web.01` inheriting its `web_01` label), blocks would route the
    wrong object to the wrong address. Moving through a temporary address with
    `terraform state mv` does it correctly.
    """

    addresses: List[str] = Field(description="Every address involved, old and new")
    state_mv: List[str] = Field(description="Commands to run, in order, instead of blocks")


class MovedBlocks(BaseModel):
    target: str
    moves: List[Move] = Field(default_factory=list)
    conflicts: List[Conflict] = Field(default_factory=list)
    #: Addresses only in the old render that no rename explains — Terraform
    #: will destroy these. Listed so nobody assumes the blocks cover them.
    unmatched_removed: List[str] = Field(default_factory=list)
    #: Addresses only in the new render with no predecessor — Terraform will
    #: create these.
    unmatched_added: List[str] = Field(default_factory=list)

    def to_hcl(self) -> str:
        if not self.moves:
            return ""
        header = (
            "# Generated by `iactranslate diff --moved-tf`.\n"
            "# Each block tells Terraform that a machine renamed at the source is the\n"
            "# same resource, so it is updated in place instead of destroyed and\n"
            "# recreated. Review `terraform plan` before applying; these blocks can be\n"
            "# deleted once every state that needed them has been migrated.\n"
        )
        blocks = [
            f"# {m.vm_name}\nmoved {{\n  from = {m.from_address}\n  to   = {m.to_address}\n}}\n"
            for m in self.moves
        ]
        return header + "\n" + "\n".join(blocks)


def _addresses(vms: List[NormalizedVM], target_name: str, region: Optional[str]) -> Tuple[Set[Address], Dict[str, str]]:
    """Every resource address the generated Terraform declares, and vm_name -> label."""
    target = get_target(target_name)
    plan = build_migration_plan(vms, project_name="moves", target=target, region=region)
    found: Set[Address] = set()
    for name, content in build_files(plan, target).items():
        if name.endswith(".tf"):
            found.update(_RESOURCE.findall(content))
    return found, {c.vm_name: c.resource_name for c in plan.compute}


def _relabel(label: str, old: str, new: str) -> Optional[str]:
    """`label` with the machine label `old` replaced by `new`, on `_` boundaries.

    Covers how templates derive per-machine labels: the machine's own label,
    `<label>_data_2` for its disks, `<lb>_<port>_<label>` for load-balancer
    membership. Returns None when `old` is not a whole component of `label`.
    """
    if label == old:
        return new
    if label.startswith(old + "_"):
        return new + label[len(old):]
    if label.endswith("_" + old):
        return label[: -len(old)] + new
    marker = "_" + old + "_"
    if marker in label:
        return label.replace(marker, "_" + new + "_", 1)
    return None


def _owner(label: str, machine_labels: List[str]) -> Optional[str]:
    """Which machine an address label belongs to, by its label as a component.

    Longest first: `web_01_2` is a machine of its own, not `web_01` + `_2`.
    """
    for machine in machine_labels:
        if _relabel(label, machine, machine) is not None:
            return machine
    return None


def _components(moves: List[Move]) -> List[List[Move]]:
    """Group moves whose addresses touch, so each group is resolved as a unit."""
    groups: List[List[Move]] = []
    for m in moves:
        touching = [g for g in groups
                    if any(m.from_address in (o.from_address, o.to_address)
                           or m.to_address in (o.from_address, o.to_address) for o in g)]
        merged = [m] + [o for g in touching for o in g]
        groups = [g for g in groups if g not in touching] + [merged]
    return groups


def _state_mv(group: List[Move]) -> List[str]:
    """Two-phase `state mv`: everything to a temporary address, then home.

    No final address can be occupied mid-way, so reuse, shifts and swaps all
    resolve the same way.
    """
    ordered = sorted(group, key=lambda m: m.from_address)
    tmp = {m.from_address: f"{m.from_address}__iactranslate_tmp" for m in ordered}
    return (
        [f"terraform state mv '{m.from_address}' '{tmp[m.from_address]}'" for m in ordered]
        + [f"terraform state mv '{tmp[m.from_address]}' '{m.to_address}'" for m in ordered]
    )


def moved_blocks(
    before: List[NormalizedVM],
    after: List[NormalizedVM],
    target: str = "aws",
    region: Optional[str] = None,
) -> MovedBlocks:
    """`moved` blocks carrying the old snapshot's Terraform state onto the new one."""
    old_addrs, old_labels = _addresses(before, target, region)
    new_addrs, new_labels = _addresses(after, target, region)

    # Machines present in both snapshots, by UUID, whose label changed.
    new_by_uuid = {v.source_uuid.lower(): v for v in after if v.source_uuid}
    relabel: Dict[str, Tuple[str, str]] = {}  # old label -> (new label, new vm_name)
    for vm in before:
        twin = new_by_uuid.get(vm.source_uuid.lower()) if vm.source_uuid else None
        if twin is None:
            continue
        old_label, new_label = old_labels.get(vm.vm_name), new_labels.get(twin.vm_name)
        if old_label and new_label and old_label != new_label:
            relabel[old_label] = (new_label, twin.vm_name)

    # Attribute every old address to its machine — including addresses that
    # still exist in the new render, because a reused label means the object
    # there now belongs to someone else.
    machines = sorted(old_labels.values(), key=len, reverse=True)
    moves: List[Move] = []
    for rtype, label in sorted(old_addrs):
        owner = _owner(label, machines)
        if owner not in relabel:
            continue
        new_label, vm_name = relabel[owner]
        candidate = _relabel(label, owner, new_label)
        if candidate is not None and (rtype, candidate) in new_addrs:
            moves.append(Move(from_address=f"{rtype}.{label}",
                              to_address=f"{rtype}.{candidate}", vm_name=vm_name))

    # A destination that existed before and is not itself being vacated holds
    # some other machine's object. Moving onto it would be wrong whatever the
    # mechanism, so the substitution matched by coincidence: drop it.
    vacated = {m.from_address for m in moves}
    old_flat = {f"{t}.{lbl}" for t, lbl in old_addrs}
    moves = [m for m in moves if m.to_address not in old_flat or m.to_address in vacated]

    # A move whose source or destination is another move's address would be
    # chained by Terraform. Those groups become `state mv` instructions.
    plain: List[Move] = []
    conflicts: List[Conflict] = []
    for group in _components(moves):
        froms = {m.from_address for m in group}
        if len(group) > 1 and froms & {m.to_address for m in group}:
            conflicts.append(Conflict(
                addresses=sorted(froms | {m.to_address for m in group}),
                state_mv=_state_mv(group),
            ))
        else:
            plain.extend(group)

    moved_from = {m.from_address for m in moves}
    moved_to = {m.to_address for m in moves}
    return MovedBlocks(
        target=target,
        moves=sorted(plain, key=lambda m: m.from_address),
        conflicts=sorted(conflicts, key=lambda c: c.addresses),
        unmatched_removed=sorted(f"{t}.{lbl}" for t, lbl in old_addrs - new_addrs
                                 if f"{t}.{lbl}" not in moved_from),
        unmatched_added=sorted(f"{t}.{lbl}" for t, lbl in new_addrs - old_addrs
                               if f"{t}.{lbl}" not in moved_to),
    )
